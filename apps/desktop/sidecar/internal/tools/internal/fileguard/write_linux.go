package fileguard

import "golang.org/x/sys/unix"

// bsdGroups is false: a new file takes the creator's group, or its directory's
// under a setgid directory.
const bsdGroups = false

// renameNoReplace renames from to to, failing with EEXIST on a file there.
var renameNoReplace = func(from, to string) error {
	return unix.Renameat2(unix.AT_FDCWD, from, unix.AT_FDCWD, to, unix.RENAME_NOREPLACE)
}
